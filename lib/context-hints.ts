export function controlHint(label: string, kind: string, href = '') {
  for (const [pattern, text] of hints) if (pattern.test(label)) return text;
  if (href.startsWith('/help/'))
    return 'يفتح معاينة الشرح. إرسال إجابة للعميل يتم من زر مشاركة الإجابة.';
  if (href.includes('/admin')) return 'يفتح القسم المحدد داخل مساحة الفريق حسب صلاحيات حسابك.';
  if (kind === 'checkbox') return 'يضيف أو يستبعد الاختيار المحدد؛ راجع النتيجة قبل الحفظ.';
  if (kind === 'select')
    return `اختار ${label || 'القيمة المناسبة'} من القائمة لتحديد النطاق المطلوب.`;
  if (kind === 'textarea' || kind === 'input')
    return `اكتب ${label || 'البيانات المطلوبة'} في الحقل؛ التغييرات لا تتحفظ إلا عند الحفظ.`;
  return label
    ? `يفتح أو ينفذ «${label}». راجع البيانات المعروضة قبل تأكيد أي تغيير.`
    : 'استخدم الإجراء المحدد؛ راجع البيانات قبل تأكيد أي تغيير.';
}
